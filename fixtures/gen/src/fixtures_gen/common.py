"""Shared helpers for deterministic synthetic DXF fixture generation.

Determinism strategy (see fixtures/README.md "Decisions"):

* ``ezdxf.options.write_fixed_meta_data_for_testing = True`` makes ezdxf
  write a fixed ``$TDCREATE``/``$TDUPDATE`` (2000-01-01) and all-zero
  ``$FINGERPRINTGUID``/``$VERSIONGUID`` instead of the current time / random
  GUIDs on every ``saveas()``.
* All randomness goes through ``random.Random(seed)`` instances created by
  :func:`make_rng`, seeded from a single module-level ``SEED`` plus the
  fixture id, so every fixture's random stream is independent and stable
  regardless of the order fixtures are generated in.
* Every fixture module creates entities in a fixed, non-parallel order
  (plain ``for`` loops over pre-built lists, never over a ``set`` or an
  unordered ``dict``), so ezdxf's incrementing handle counter assigns the
  same handle to the same entity on every run.
"""

from __future__ import annotations

import random
from collections.abc import Iterable
from pathlib import Path
from typing import Any

import ezdxf
from ezdxf.document import Drawing

# Must be set before any Drawing is created/saved.
ezdxf.options.write_fixed_meta_data_for_testing = True

#: Master seed for the whole fixture set. Changing this changes every
#: generated byte -- bump it only with a matching README/Decisions update.
SEED = 20260311

#: $INSUNITS = 4 -> millimeters (ezdxf.units.MM), matches Korean drawing practice.
INSUNITS_MM = 4

#: Standard layer palette used across fixtures, per the brief's "국내 도면 관행"
#: list. color = AutoCAD Color Index (ACI), linetype must be loaded via
#: ``ezdxf.new(..., setup=True)``.
LAYER_DEFS: dict[str, dict[str, Any]] = {
    "0": {"color": 7, "linetype": "CONTINUOUS", "desc": "default"},
    "S-COL": {"color": 1, "linetype": "CONTINUOUS", "desc": "structural column"},
    "S-BEAM": {"color": 5, "linetype": "DASHED", "desc": "structural beam centerline"},
    "S-WALL": {"color": 3, "linetype": "CONTINUOUS", "desc": "structural wall"},
    "S-SLAB": {"color": 2, "linetype": "CONTINUOUS", "desc": "structural slab"},
    "A-WALL": {"color": 7, "linetype": "CONTINUOUS", "desc": "architectural wall"},
    "A-DOOR": {"color": 4, "linetype": "CONTINUOUS", "desc": "door"},
    "A-WIND": {"color": 6, "linetype": "CONTINUOUS", "desc": "window"},
    "A-TEXT": {"color": 7, "linetype": "CONTINUOUS", "desc": "annotation text"},
    "A-DIM": {"color": 3, "linetype": "CONTINUOUS", "desc": "dimensions"},
    "X-GRID": {"color": 8, "linetype": "CENTER", "desc": "column grid"},
    "X-TITLE": {"color": 7, "linetype": "CONTINUOUS", "desc": "title block / border"},
}


def make_rng(fixture_id: str, variant: str = "base") -> random.Random:
    """Return a deterministic RNG stream private to one fixture/variant.

    Using a string seed derived from the fixture id keeps every fixture's
    random sequence independent of call order across the whole generator run.
    """
    return random.Random(f"{SEED}:{fixture_id}:{variant}")


def new_doc(version: str = "R2018", encoding: str | None = None) -> Drawing:
    """Create a new document with fixed metadata and standard resources loaded."""
    doc = ezdxf.new(version, setup=True)
    doc.header["$INSUNITS"] = INSUNITS_MM
    doc.header["$MEASUREMENT"] = 1
    doc.header["$LUNITS"] = 2
    doc.header["$LUPREC"] = 2
    if encoding:
        doc.encoding = encoding
    return doc


def ensure_layers(doc: Drawing, names: Iterable[str]) -> None:
    """Create any of ``names`` not already present, using :data:`LAYER_DEFS`."""
    for name in names:
        if name in doc.layers:
            continue
        defn = LAYER_DEFS.get(name, {"color": 7, "linetype": "CONTINUOUS"})
        doc.layers.add(name=name, color=defn["color"], linetype=defn["linetype"])


def save(doc: Drawing, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    doc.saveas(str(path))


# DXF versions that do not support certain modern entity types. Used by
# fixtures to decide what to omit for the R2000 variant and to record why.
R2000_UNSUPPORTED = {
    "MULTILEADER": "MLEADER requires DXF R2007 (AC1021) or newer",
    "GRADIENT_HATCH": "gradient-filled HATCH requires DXF R2004 (AC1018) or newer",
}


def version_supports(version: str, feature: str) -> bool:
    if feature == "MULTILEADER":
        return version not in ("R12", "R2000")
    if feature == "GRADIENT_HATCH":
        return version not in ("R12", "R2000")
    return True
