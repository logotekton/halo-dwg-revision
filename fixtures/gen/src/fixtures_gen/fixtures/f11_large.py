"""F11/F12 -- large fixtures: F06 (structural plan) replicated across many
spatial tiles into one document, to exercise viewer/engine performance paths.

F11 targets ~200,000 entities (generated by default), F12 targets
~1,000,000 entities (only with ``--large``, never committed). Both reuse
:mod:`fixtures_gen.fixtures.f06_structural_plan` per tile, offsetting each
tile spatially and suffixing every tag/label with ``-T{index}`` so tiles
never collide on name or position.
"""

from __future__ import annotations

import math
import random

from fixtures_gen.base import BuildResult
from fixtures_gen.common import new_doc
from fixtures_gen.fixtures import f06_structural_plan as f06

TILE_STEP_X = 40000.0
TILE_STEP_Y = 30000.0


def _measure_entities_per_tile(version: str) -> int:
    probe_doc = new_doc(version)
    f06.build(version, random.Random("probe"), build_title=False, doc=probe_doc)
    return len(list(probe_doc.modelspace()))


def build(version: str, rng: random.Random, target_entities: int) -> BuildResult:
    doc = new_doc(version)
    per_tile = _measure_entities_per_tile(version)
    tile_count = max(1, math.ceil(target_entities / per_tile))
    cols = max(1, math.ceil(math.sqrt(tile_count)))
    rows = math.ceil(tile_count / cols)

    idx = 0
    for r in range(rows):
        for c in range(cols):
            if idx >= tile_count:
                break
            offset = (c * TILE_STEP_X, r * TILE_STEP_Y)
            f06.build(
                version,
                rng,
                tile_offset=offset,
                tag_suffix=f"-T{idx:05d}",
                build_title=(idx == 0),
                doc=doc,
            )
            idx += 1

    total_entities = len(list(doc.modelspace()))
    extra = {
        "tile_count": tile_count,
        "tile_grid": {"cols": cols, "rows": rows, "step_x": TILE_STEP_X, "step_y": TILE_STEP_Y},
        "entities_per_tile": per_tile,
        "target_entities": target_entities,
        "actual_entity_count": total_entities,
        "tile_source": "fixtures_gen.fixtures.f06_structural_plan.build",
        "tile_offset_formula": (
            "(col * step_x, row * step_y), row-major, col = index % cols, row = index // cols"
        ),
        "note": (
            "Per-tile member placement (columns/beams/grid) follows the same "
            "schema as F06.json's extra, offset by this tile's (tile_offset) "
            "and suffixed with '-T{index:05d}' on every tag/label -- not "
            "enumerated here to keep this truth file small."
        ),
    }
    return BuildResult(doc=doc, extra=extra)
